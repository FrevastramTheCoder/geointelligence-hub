/**
 * GEE CODE GENERATOR — turns a structured plan into runnable Earth Engine code.
 * Mirrors the backend datasets/formulas (no invented assets). JS + Python.
 * plan: { backend, parameters } from geoaiPlanner.
 */

const S2 = 'COPERNICUS/S2_SR_HARMONIZED';
const L8 = 'LANDSAT/LC08/C02/T1_L2';

function compositeJS(source, year, cloud) {
  if (source === 'sentinel2') {
    return `var col = ee.ImageCollection('${S2}')
  .filterBounds(aoi).filterDate('${year}-01-01', '${year}-12-31')
  .filter(ee.Filter.lte('CLOUDY_PIXEL_PERCENTAGE', ${cloud}))
  .map(function(i) {
    var qa = i.select('QA60');
    var mask = qa.bitwiseAnd(1<<10).eq(0).and(qa.bitwiseAnd(1<<11).eq(0));
    return i.updateMask(mask).divide(10000);
  });
var img = col.median().clip(aoi);`;
  }
  return `var col = ee.ImageCollection('${L8}')
  .filterBounds(aoi).filterDate('${year}-01-01', '${year}-12-31')
  .filter(ee.Filter.lte('CLOUD_COVER', ${cloud}))
  .map(function(i) {
    var qa = i.select('QA_PIXEL');
    var mask = qa.bitwiseAnd(1<<3).eq(0).and(qa.bitwiseAnd(1<<4).eq(0));
    return i.updateMask(mask).multiply(0.0000275).add(-0.2);
  });
var img = col.median().clip(aoi);`;
}

const INDEX_EXPR = {
  NDVI: { bands: ['NIR', 'RED'], js: 'img.normalizedDifference([NIR, RED]).rename(INDEX)' },
  NDWI: { js: 'img.normalizedDifference([G, NIR]).rename(INDEX)' },
  MNDWI: { js: 'img.normalizedDifference([G, SWIR1]).rename(INDEX)' },
  SAVI: { js: "img.expression('((NIR - RED) / (NIR + RED + 0.5)) * 1.5', {NIR: img.select(NIR), RED: img.select(RED)}).rename(INDEX)" },
  EVI: { js: "img.expression('2.5 * ((NIR - RED) / (NIR + 6 * RED - 7.5 * BLUE + 1))', {NIR: img.select(NIR), RED: img.select(RED), BLUE: img.select(BLUE)}).rename(INDEX)" },
  NDBI: { js: 'img.normalizedDifference([SWIR1, NIR]).rename(INDEX)' },
};

function bandsFor(source) {
  return source === 'sentinel2'
    ? { NIR: "'B8'", RED: "'B4'", G: "'B3'", BLUE: "'B2'", SWIR1: "'B11'", SWIR2: "'B12'", RE: "'B5'" }
    : { NIR: "'SR_B5'", RED: "'SR_B4'", G: "'SR_B3'", BLUE: "'SR_B2'", SWIR1: "'SR_B6'", SWIR2: "'SR_B7'", RE: null };
}

export function generateGEECode(plan) {
  const backend = plan.backend || plan.intent;
  const p = plan.parameters || {};
  const year = p.year || 2024;
  const year2 = p.year2 || 2020;
  const source = p.source || 'sentinel2';
  const B = bandsFor(source);
  const head = `// Generated by GeoIntelligence Hub GIS AI Assistant
// Analysis: ${backend} | Year: ${year} | Source: ${source}
// Draw a polygon as 'aoi' (Geometry) or replace with your AOI import.
var aoi = /* your polygon, e.g. ee.Geometry.Polygon([...]) */;
`;
  let jsBody = '';
  const indexName = (p.index || backend || '').toUpperCase();
  const knownIdx = INDEX_EXPR[indexName];

  if (['ndvi', 'ndwi', 'evi', 'savi', 'ndbi'].includes(backend) || (backend === 'spectral_index' && knownIdx)) {
    const idx = backend === 'spectral_index' ? indexName : backend.toUpperCase();
    const expr = (INDEX_EXPR[idx] || INDEX_EXPR.NDVI).js
      .replace(/NIR/g, B.NIR).replace(/RED/g, B.RED).replace(/SWIR1/g, B.SWIR1)
      .replace(/SWIR2/g, B.SWIR2).replace(/BLUE/g, B.BLUE).replace(/G\b/g, B.G)
      .replace(/INDEX/g, `'${idx}'`);
    jsBody = `${compositeJS(source, year, p.maxCloud ?? 30)}
var result = ${expr};
Map.addLayer(result, {min: -0.2, max: 0.8, palette: ['red', 'yellow', 'green']}, '${idx} ${year}');
var stats = result.reduceRegion({reducer: ee.Reducer.mean(), geometry: aoi, scale: 10, maxPixels: 1e9, bestEffort: true});
print('${idx} stats', stats);`;
  } else if (backend === 'spectral_index') {
    jsBody = `${compositeJS(source, year, p.maxCloud ?? 30)}
// Index '${indexName}': implement with img.expression() using ${source} bands.
// Band reference: ${JSON.stringify(B)}
// Example (MNDWI): img.normalizedDifference([${B.G}, ${B.SWIR1}])`;
  } else if (backend === 'landcover') {
    const n = p.numClasses || 5;
    const names = (p.classNames || []).join(', ') || 'default 5-class schema';
    jsBody = `${compositeJS(source, year, p.maxCloud ?? 30)}
var ref = ee.Image('ESA/WorldCover/v200/2021').select('Map').clip(aoi);
// Training labels remapped to ${n} classes (${names}).
var training = img.addBands(ref.rename('lc'))
  .stratifiedSample({numPoints: 80, classBand: 'lc', region: aoi, scale: 10, seed: 42, geometries: true});
var classifier = ee.Classifier.smileRandomForest(150)
  .train(training.randomColumn('r', 42).filter(ee.Filter.lt('r', 0.7)), 'lc', img.bandNames());
var classified = img.classify(classifier);
Map.addLayer(classified, {min: 0, max: ${n - 1}}, 'LULC ${year}');
// Validate on the 30% holdout before trusting accuracy:
var test = training.filter(ee.Filter.gte('r', 0.7));
var cm = test.classify(classifier).errorMatrix('lc', 'classification');
print('Overall accuracy', cm.accuracy(), 'Kappa', cm.kappa());`;
  } else if (backend === 'elevation' || backend === 'slope' || backend === 'aspect' || backend === 'hillshade') {
    const fn = { elevation: "ee.Image('USGS/SRTMGL1_003').clip(aoi)",
      slope: 'ee.Terrain.slope(ee.Image(\'USGS/SRTMGL1_003\').clip(aoi))',
      aspect: 'ee.Terrain.aspect(ee.Image(\'USGS/SRTMGL1_003\').clip(aoi))',
      hillshade: 'ee.Terrain.hillshade(ee.Image(\'USGS/SRTMGL1_003\').clip(aoi))' }[backend];
    jsBody = `var result = ${fn};
Map.addLayer(result, {}, '${backend}');
print('${backend} mean', result.reduceRegion({reducer: ee.Reducer.mean(), geometry: aoi, scale: 30, maxPixels: 1e9}));`;
  } else if (backend === 'rainfall') {
    jsBody = `var rain = ee.ImageCollection('UCSB-CHG/CHIRPS/DAILY')
  .filterBounds(aoi).filter(ee.Filter.calendarRange(${year}, ${year}, 'year'))
  .select('precipitation').sum().clip(aoi);
Map.addLayer(rain, {min: 0, max: 2000, palette: ['white', 'cyan', 'blue']}, 'Rainfall ${year}');
print('Mean annual rain (mm)', rain.reduceRegion({reducer: ee.Reducer.mean(), geometry: aoi, scale: 5000, maxPixels: 1e9}));`;
  } else if (backend === 'lst') {
    jsBody = `var lst = ee.ImageCollection('MODIS/061/MOD11A1')
  .filterBounds(aoi).filter(ee.Filter.calendarRange(${year}, ${year}, 'year'))
  .select('LST_Day_1km').median().multiply(0.02).subtract(273.15).clip(aoi);
Map.addLayer(lst, {min: 15, max: 45, palette: ['blue', 'cyan', 'yellow', 'red']}, 'LST ${year}');`;
  } else if (backend === 'flood_mapping') {
    jsBody = `var s1 = ee.ImageCollection('COPERNICUS/S1_GRD')
  .filterBounds(aoi).filterDate('${year}-01-01', '${year}-12-31')
  .filter(ee.Filter.eq('instrumentMode', 'IW'))
  .filter(ee.Filter.listContains('transmitterReceiverPolarisation', 'VH'))
  .select('VH').median().clip(aoi);
var water = s1.lt(-18).selfMask();
Map.addLayer(water, {palette: ['0000CD']}, 'Flood extent ${year}');`;
  } else if (backend === 'change' || backend === 'urban_growth') {
    jsBody = `${compositeJS(source, year2, 30).replace(/var img =.*/, `var img1 = col.median().clip(aoi);`)}
${compositeJS(source, year, 30).replace(/var img =.*/, `var img2 = col.median().clip(aoi);`).replace(/var col =/, 'var col2 =').replace(/col\.median/, 'col2.median')}
var diff = img2.normalizedDifference([${B.NIR}, ${B.RED}]).subtract(img1.normalizedDifference([${B.NIR}, ${B.RED}]));
Map.addLayer(diff, {min: -0.5, max: 0.5, palette: ['red', 'yellow', 'white', 'green']}, 'Change ${year2}-${year}');`;
  } else {
    jsBody = `// Backend id '${backend}' — generic pattern (same datasets the app uses):
${compositeJS(source, year, 30)}
Map.addLayer(img, {bands: [${B.RED}, ${B.G}, ${B.NIR}], min: 0, max: 0.3}, 'Composite ${year}');`;
  }

  const javascript = `${head}\n${jsBody}\n`;
  const python = javascript
    .replace(/var /g, '')
    .replace(/Map\.addLayer/g, '# map.add_ee_layer')
    .replace(/print\(/g, 'print(');
  return { javascript, python };
}
